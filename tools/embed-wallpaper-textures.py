"""Regenerate assets/data/wallpaper-textures.js from the WebGL wallpaper images.

Only needed when the wallpaper images change. The output lets the animated
wallpaper run when the site is opened directly from disk (file://), where
browsers refuse to upload local image files to WebGL.
"""
import base64
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
IMAGES = {
    'projects': 'assets/images/projects-kingdom-wallpaper.webp',
    'skills': 'assets/images/skills-kingdom-wallpaper.webp',
}
OUTPUT = ROOT / 'assets/data/wallpaper-textures.js'


def to_data_uri(relative_path):
    data = (ROOT / relative_path).read_bytes()
    return 'data:image/webp;base64,' + base64.b64encode(data).decode('ascii')


def main():
    lines = [
        '// Generated by tools/embed-wallpaper-textures.py. Do not edit by hand.',
        '// prettier-ignore',
        'window.WALLPAPER_TEXTURES = {',
    ]
    for scene, path in IMAGES.items():
        lines.append(f'  {scene}: {json.dumps(to_data_uri(path))},')
    lines.append('};')
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'wrote {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
